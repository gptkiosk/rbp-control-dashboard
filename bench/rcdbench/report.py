"""Aggregate cell results into per-hardware-target tables (median / p95) and CSV/JSON."""
from __future__ import annotations

import csv
import json
from pathlib import Path

from .stats import median, p95

STORY_FIELDS = ["target", "runtime", "llm_model", "story", "kind", "ok", "structured_ok", "status", "startup_s",
                "wall_s", "cpu_s", "peak_rss_kb", "steady_rss_kb", "timeout_overshoot_s", "cancel_ack_s",
                "cancel_to_terminal_s", "cost_usd", "input_tokens", "output_tokens", "pin_violation",
                "skipped", "error"]


def target_label(hw, override=None):
    if override:
        return override
    return (hw.get("model") or f'{hw.get("arch")}-{hw.get("os") or "unknown-host"}').strip()


def _col(rows, key, scale=1.0):
    return [r[key] / scale for r in rows if r.get(key) is not None]


def _fmt(v, nd=2):
    return "n/a" if v is None else f"{v:.{nd}f}"


def _mp(values, nd=2):
    return f"{_fmt(median(values), nd)} / {_fmt(p95(values), nd)}"


def cell_summary(cell):
    rows = [s for s in cell.get("stories", []) if not s.get("skipped")]
    structured = [s for s in rows if s.get("expected_structured")]
    ok_cpu = [s["cpu_s"] / s["wall_s"] * 100 for s in rows if s.get("cpu_s") is not None and s.get("wall_s")]
    cg = cell.get("cgroup", {})
    return {
        "runtime": cell["runtime"], "llm_model": cell["llm_model"], "status": cell["status"], "reason": cell.get("reason"),
        "live": cell.get("live"), "stories_run": len(rows), "stories_skipped": len(cell.get("stories", [])) - len(rows),
        "story_success": sum(bool(s["ok"]) for s in rows) / len(rows) if rows else None,
        "structured_success": (sum(bool(s["structured_ok"]) for s in structured) / len(structured)) if structured else None,
        "pin_violations": sum(bool(s.get("pin_violation")) for s in rows),
        "startup_s": [s["startup_s"] for s in rows if s.get("startup_s") is not None],
        "peak_rss_mib": _col(rows, "peak_rss_kb", 1024), "steady_rss_mib": _col(rows, "steady_rss_kb", 1024),
        "cgroup_peak_mib": (cg["memory_peak_bytes"] / 1048576) if cg.get("memory_peak_bytes") is not None else None,
        "cgroup_peak_reset": cg.get("peak_reset"),
        "cpu_pct": ok_cpu, "timeout_overshoot_s": _col(rows, "timeout_overshoot_s"),
        "cancel_ack_s": _col(rows, "cancel_ack_s"), "cancel_to_terminal_s": _col(rows, "cancel_to_terminal_s"),
        "cost_usd": cell.get("cost_usd_total", 0.0),
    }


def render(runs, out_md):
    """runs: list of {'target': str, 'hardware': {...}, 'cells': [...], 'backend': {...}|None, 'run_id': str}."""
    by_target = {}
    for run in runs:
        by_target.setdefault(run["target"], []).append(run)
    lines = ["# RCD runtime benchmark report", "",
             "Generated by `bench/run.py`. Cells are `median / p95` over the stories in that cell. "
             "`n/a` = not measured (never estimated). See `bench/README.md` for the method.", ""]
    total_cost = 0.0
    for target, target_runs in sorted(by_target.items()):
        hw = target_runs[-1]["hardware"]
        lines += [f"## Hardware target: {target}", "",
                  f'- OS: {hw.get("os")}; kernel {hw.get("kernel")}; {hw.get("arch")}; {hw.get("cpus")} CPUs; '
                  f'RAM {_fmt((hw.get("memory_total_kb") or 0) / 1048576, 2) if hw.get("memory_total_kb") else "n/a"} GiB',
                  f'- Runs: {", ".join(r["run_id"] for r in target_runs)}', ""]
        backends = [r["backend"] for r in target_runs if r.get("backend")]
        if backends:
            b = backends[-1]
            if b["status"] == "ok":
                lines += [f'- Backend (apps/api, no collector/dispatcher): idle RSS {b["idle_rss_kb_median"] / 1024:.1f} MiB '
                          f'(max {b["idle_rss_kb_max"] / 1024:.1f}); loaded ({b["load_workers"]} clients, '
                          f'{b["load_requests"]} requests / {b["load_seconds"]}s) median {b["loaded_rss_kb_median"] / 1024:.1f} / '
                          f'peak {b["loaded_rss_kb_peak"] / 1024:.1f} MiB; startup {b["startup_s"]:.1f}s', ""]
            else:
                lines += [f'- Backend memory: **{b["status"]}** — {b["reason"]}', ""]
        lines += ["| Runtime | LLM model | Status | Stories | Success | Structured ok | Pin viol. | Startup s | Peak RSS MiB | Steady RSS MiB | cgroup peak MiB | CPU % | Timeout overshoot s | Cancel ack s | Cancel→terminal s | Cost USD |",
                  "|" + "---|" * 16]
        for run in target_runs:
            for cell in run["cells"]:
                s = cell_summary(cell)
                total_cost += s["cost_usd"] or 0
                if s["status"] != "ok":
                    lines.append(f'| {s["runtime"]} | {s["llm_model"]} | **{s["status"]}**: {(s["reason"] or "")[:80]} |' + " |" * 13)
                    continue
                pct = lambda v: "n/a" if v is None else f"{v * 100:.0f}%"
                synthetic = "" if s["live"] else " ⚠ synthetic"
                skipped = s["stories_skipped"]
                skip_note = f" (+{skipped} skipped: cost cap)" if skipped else ""
                lines.append(
                    f'| {s["runtime"]}{synthetic} | {s["llm_model"]} | ok | {s["stories_run"]}{skip_note}'
                    f' | {pct(s["story_success"])} | {pct(s["structured_success"])} | {s["pin_violations"]} | '
                    f'{_mp(s["startup_s"], 3)} | {_mp(s["peak_rss_mib"], 1)} | {_mp(s["steady_rss_mib"], 1)} | '
                    f'{_fmt(s["cgroup_peak_mib"], 1)} | {_mp(s["cpu_pct"], 0)} | {_mp(s["timeout_overshoot_s"], 3)} | '
                    f'{_mp(s["cancel_ack_s"], 3)} | {_mp(s["cancel_to_terminal_s"], 3)} | {s["cost_usd"]:.4f} |')
        lines.append("")
    lines += [f"**Total OpenRouter spend across all listed runs: ${total_cost:.4f}** "
              "(sum of independent provider receipts).", ""]
    Path(out_md).write_text("\n".join(lines))


def write_run(run_dir, run):
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "results.json").write_text(json.dumps(run, indent=1))
    with open(run_dir / "stories.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, STORY_FIELDS, extrasaction="ignore")
        writer.writeheader()
        for cell in run["cells"]:
            for story in cell.get("stories", []):
                writer.writerow({"target": run["target"], "runtime": cell["runtime"],
                                 "llm_model": cell["llm_model"], **story})


def load_runs(results_dir):
    return [json.loads(p.read_text()) for p in sorted(Path(results_dir).glob("*/results.json"))]
